"""The ``agents-md`` generator (pack ``spec-core``): the chipgraph part of an `AGENTS.md`.

Optional and deterministic, no AI (DESIGN.md 4.7, DECISIONS D18/D31). From the resolved
profile and the organization rules it extends, it writes the project's conventions for
any coding agent (Codex, Cursor, Claude Code ...): blocks and instances, where files go,
naming rules, the checks to run before a PR, requirement IDs, path exceptions, data labels
and generated files.

chipgraph manages only the text between ``<!-- chipgraph:begin -->`` and
``<!-- chipgraph:end -->``; the rest of the file is the team's and is never changed.

Public API:

- :func:`render_agents_md` — the managed block's content (without the markers).
  Deterministic: sections sorted, no dates, no absolute paths, ``\\n`` line endings.
- :func:`update_agents_md` — put a block into an existing file's managed part (or append
  it, or return it alone when there is no file); malformed markers raise
  :class:`AgentsMdError`.
- :func:`agents_md_content` — both in one: the full file content to write.

The block is rendered from the Jinja2 template ``agents_md.md.j2`` through
:class:`~chipgraph.core.config.templates.TemplateSet` (DESIGN 8.6 V2), so a project can
replace one section without copying the file: ``templates.override`` in `.chipgraph.yml`
maps a block name to a file holding that one ``{% block %}``, e.g.
``templates: { override: { agents_md_checks: templates/agents_checks.j2 } }``. Block
names: ``agents_md_intro``, ``agents_md_project``, ``agents_md_layout``,
``agents_md_naming``, ``agents_md_checks``, ``agents_md_requirements``,
``agents_md_paths``, ``agents_md_data``, ``agents_md_generated``. An override may use the
same context as the pack template, plus the helpers ``code(s, cell=False)`` (a Markdown
code span) and ``text(s)`` (one line of text, safe in a table cell). Only overrides named
``agents_md.md.j2`` or starting with ``agents_md_`` are read here.
"""

from __future__ import annotations

import re
from pathlib import Path

from chipgraph.core.config import ResolvedProfile
from chipgraph.core.config.templates import TemplateLayer, TemplateSet, TemplateSetError
from chipgraph.packs.spec_core.gen.agents_md._context import build_context
from chipgraph.packs.spec_core.gen.agents_md._markers import (
    BEGIN_MARKER,
    END_MARKER,
    AgentsMdError,
    split_managed,
    update_agents_md,
)

TEMPLATE_NAME = "agents_md.md.j2"
"""The pack template's file name (and the key of a whole-file override)."""

BLOCK_PREFIX = "agents_md_"
"""Every block of the template is named with this prefix."""

NOTE = (
    "<!-- Generated by chipgraph from the project profile; do not edit this block by hand. "
    "Regenerate it with `chipgraph agents-md --write`. -->"
)
"""The one-line note that opens the managed block."""

_TEMPLATE_DIR = Path(__file__).resolve().parent

_BLANK_RUNS = re.compile(r"\n{3,}")


def code(value: object, cell: bool = False) -> str:
    """`value` as a Markdown code span; with `cell`, `|` is escaped for a table cell."""
    s = " ".join(str(value).split())
    if not s:
        return ""
    fence = "``" if "`" in s else "`"
    pad = " " if fence == "``" else ""
    if cell:
        s = s.replace("|", "\\|")
    return f"{fence}{pad}{s}{pad}{fence}"


def text(value: object) -> str:
    """`value` as one line of Markdown text, safe in a table cell.

    Only `<` (else read as an HTML tag, e.g. ``m_qnsc_<function>``) and `|` (a cell
    separator) are escaped; other Markdown in the value is kept as written.
    """
    s = " ".join(str(value).split())
    for ch in ("<", "|"):
        s = s.replace(ch, "\\" + ch)
    return s


def _normalize(rendered: str) -> str:
    lines = [line.rstrip() for line in rendered.replace("\r\n", "\n").split("\n")]
    out = _BLANK_RUNS.sub("\n\n", "\n".join(lines)).strip("\n")
    return out + "\n" if out else ""


def _template_set(resolved: ResolvedProfile, root: Path) -> TemplateSet:
    overrides = {
        name: str(path if (path := Path(value)).is_absolute() else root / path)
        for name, value in sorted(resolved.profile.templates.override.items())
        if name == TEMPLATE_NAME or name.startswith(BLOCK_PREFIX)
    }
    layers: list[TemplateLayer] = []
    if overrides:
        layers.append(TemplateLayer(name="project", override=overrides))
    layers.append(TemplateLayer(name="pack", directory=_TEMPLATE_DIR))
    return TemplateSet(layers)


def render_agents_md(resolved_profile: ResolvedProfile, root: Path) -> str:
    """The managed block's content for the project at `root`, without the markers.

    It starts with the one-line generated note, then one section per kind of profile data
    present. The same profile always gives the same bytes. Raises `AgentsMdError` if the
    naming rules cannot be read or a template override is broken.
    """
    context = build_context(resolved_profile, root)
    context["code"] = code
    context["text"] = text
    try:
        body = _template_set(resolved_profile, root).render(TEMPLATE_NAME, context)
    except TemplateSetError as exc:
        raise AgentsMdError(f"cannot render the AGENTS.md block: {exc}") from exc
    block = _normalize(body)
    if BEGIN_MARKER in block or END_MARKER in block:
        raise AgentsMdError("the rendered AGENTS.md block must not contain the chipgraph markers")
    return f"{NOTE}\n\n{block}"


def agents_md_content(existing: str | None, resolved_profile: ResolvedProfile, root: Path) -> str:
    """The full file content: `existing` with its managed block (re)generated."""
    return update_agents_md(existing, render_agents_md(resolved_profile, root))


