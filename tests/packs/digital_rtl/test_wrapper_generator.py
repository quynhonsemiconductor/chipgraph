"""M2-12: the generator `emacs_auto` (`packs/digital_rtl/wrapper/emacs.py`).

Without emacs: argument handling, the emacs command line, error messages and the
"generated" header, with a canned runner that answers like emacs would. With emacs
(skipped when it or verilog-mode is missing): the real expansion is byte-identical across
two runs, equals the committed sample, and a source written the way a model would
expands to the right instance.
"""

