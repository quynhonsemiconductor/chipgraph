@needs_emacs
def test_a_source_written_the_way_a_model_would_expands_to_the_right_instance(
    tmp_path: Path,
) -> None:
    from chipgraph.adapters.runner.local import LocalRunner

    root = make_project(tmp_path / "t", generated=False, commit=False)
    (root / SRC).write_text(model_style_source())
    result = _run(root, LocalRunner())
    assert result.status == "pass", result.issues
    text = (root / OUT).read_text()
    [inst] = instances(gen.body_of(text), "vendor_fifo")
    connected = {c.port: c.expr for c in inst.connections}
    assert connected == {
        "clk_i": "i_clk",
        "rst_ni": "i_rst_n",
        "clr_i": "i_clr",
        "testmode_i": "1'b0",
        "push_i": "i_push",
        "data_i": "i_data[7:0]",
        "full_o": "o_full",
        "pop_i": "i_pop",
        "data_o": "o_data[7:0]",
        "empty_o": "o_empty",
        "err_o": "unused_err",
    }
    assert all(c.templated for c in inst.connections)
    # the port groups the author wrote were filled in, with the widths of the parameters
    assert re.search(r"input logic \[7:0\]\s+i_data,", text)
    assert re.search(r"output logic \[7:0\]\s+o_data[,\s]", text)
    assert "logic                 unused_err;" in text  # sunk, not a port
    assert not re.search(r"output logic\s+unused_err", text)
    assert text.count("// Beginning of automatic") == 3  # inputs, outputs, wires


