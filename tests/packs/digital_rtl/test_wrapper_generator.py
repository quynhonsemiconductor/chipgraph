def test_a_missing_source_fails_and_a_missing_ip_file_is_infra(root: Path) -> None:
    (root / SRC).unlink()
    result = _run(root, CannedRunner(expanded=CANNED))
    assert (result.status, result.issues[0].rule) == ("fail", "wrap.src_missing")
    (root / SRC).write_text(source_text())
