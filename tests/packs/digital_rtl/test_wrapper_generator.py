@needs_emacs
@pytest.mark.parametrize("where", ["source", "mode_line", "vendor_ip"])
def test_file_local_eval_never_runs(tmp_path: Path, where: str) -> None:
    """verilog-mode's batch command sets `enable-local-eval` itself and rereads the
    `Local Variables:` block of the source and of the IP files it reads: the generator
    must make them inert, or a source (written by a model) could run code."""
    from chipgraph.adapters.runner.local import LocalRunner

    root = make_project(tmp_path / "t", generated=False, commit=False)
    mark = tmp_path / "pwned"
    form = f'(write-region "x" nil "{mark}")'
    block = f"\n// Local Variables:\n// eval: {form}\n// End:\n"
    if where == "source":
        (root / SRC).write_text(source_text() + block)
    elif where == "mode_line":
        (root / SRC).write_text(f"// -*- eval: {form} -*-\n" + source_text())
    else:
        ip = root / "vendor/vendor_fifo/vendor_fifo.sv"
        ip.write_text(ip.read_text() + block)
    before = (root / "vendor/vendor_fifo/vendor_fifo.sv").read_bytes()
    result = _run(root, LocalRunner())
    assert result.status == "pass", result.issues
    assert not mark.exists()
    assert (
        root / "vendor/vendor_fifo/vendor_fifo.sv"
    ).read_bytes() == before or where == "vendor_ip"


def test_neutralize_keeps_the_line_count_and_removes_the_markers() -> None:
    text = "// -*- eval: (x) -*-\nmodule m; endmodule\n// Local Variables:\n// eval: (y)\n// End:\n"
    out = gen.neutralize(text)
    assert out.count("\n") == text.count("\n")
    assert (
        "Local Variables:" not in out and "-*-" not in out and "local variables:" not in out.lower()
    )
    assert gen.neutralize("// LOCAL  VARIABLES :\n").lower().count("variables :") == 0
    assert gen.neutralize("module m; endmodule\n") == "module m; endmodule\n"
