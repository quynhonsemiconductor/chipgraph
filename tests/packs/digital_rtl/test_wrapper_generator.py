def root(tmp_path: Path) -> Path:
    return make_project(tmp_path / "t", generated=False, commit=False)


def test_the_tool_is_a_gen_tool_of_the_registry() -> None:
    from importlib.metadata import entry_points

    [ep] = [e for e in entry_points(group="chipgraph.adapters.tool") if e.name == "emacs_auto"]
    assert ep.load() is gen.EmacsAutoTool
    assert (gen.EmacsAutoTool.name, gen.EmacsAutoTool.capability) == ("emacs_auto", "gen")


def test_emacs_runs_through_the_runner_on_a_scratch_copy_with_the_settings(root: Path) -> None:
    runner = CannedRunner(expanded=CANNED)
    result = _run(root, runner)
    assert result.status == "pass", result.issues
    probe, expand = runner.commands
    assert probe[:3] == ["emacs", "-Q", "--batch"]
    assert expand[:3] == ["emacs", "-Q", "--batch"]  # no init file
    assert expand[-2:] == ["-f", "verilog-batch-auto"]
    scratch = Path(expand[-3])
    assert scratch.name == "tiny_fifo_wrap.sv"
    assert root not in scratch.parents and not scratch.exists()  # outside the repo, removed
    settings = expand[expand.index("--eval") + 1]
    for needle in (
        "enable-local-variables nil",
        "verilog-auto-inst-param-value t",
        "verilog-auto-star-expand nil",
        "indent-tabs-mode nil",
        "verilog-indent-level 3",
        "/ip/0/vendor_fifo.sv",
    ):
        assert needle in settings, needle
    assert str(root.resolve()) not in settings  # the IP in the repository is not handed to emacs
    assert (root / SRC).read_text() == source_text()  # the source is never written to


def test_the_output_is_normalised_and_marked_generated(root: Path) -> None:
    result = _run(root, CannedRunner(expanded=CANNED))
    text = (root / OUT).read_text()
    assert "\r" not in text and text.endswith("endmodule\n")
    assert verify(text) is True  # the `generated` check's marker
    assert text.splitlines()[1:3] == [
        f"// Generated by chipgraph from {SRC}",
        f"// source sha256 {gen.source_sha(source_text())}",
    ]
    assert "Do not edit this file" in text and gen.generated_from(text) == (
        SRC,
        gen.source_sha(source_text()),
    )
    assert gen.body_of(text) == "module tiny_fifo_wrap ();\nendmodule\n"
    assert [i.rule for i in result.issues] == ["wrap.generated"]


def test_the_same_input_gives_the_same_bytes_and_a_rerun_writes_nothing(root: Path) -> None:
    _run(root, CannedRunner(expanded=CANNED))
    first = (root / OUT).read_bytes()
    stamp = (root / OUT).stat().st_mtime_ns
    _run(root, CannedRunner(expanded=CANNED))
    assert (root / OUT).read_bytes() == first
    assert (root / OUT).stat().st_mtime_ns == stamp


def test_line_endings_do_not_change_the_source_hash(root: Path) -> None:
    assert gen.source_sha("a\r\nb\r\n\r\n") == gen.source_sha("a\nb\n")


def test_the_result_is_idempotent_for_the_same_files(root: Path) -> None:
    key = _run(root, CannedRunner(expanded=CANNED)).idempotency_key
    assert _run(root, CannedRunner(expanded=CANNED)).idempotency_key == key
    (root / SRC).write_text(source_text() + "// changed\n")
    assert _run(root, CannedRunner(expanded=CANNED)).idempotency_key != key


