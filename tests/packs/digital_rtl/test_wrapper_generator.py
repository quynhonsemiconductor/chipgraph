CANNED = "module tiny_fifo_wrap ();\r\nendmodule\r\n\r\n\r\n"


def _spec(**args: object) -> CheckSpec:
    return CheckSpec(id="emacs_auto", capability="gen", adapter="emacs_auto", args=args)


def _run(root: Path, runner: object, spec: CheckSpec | None = None, **params: str):  # type: ignore[no-untyped-def]
    tool = gen.EmacsAutoTool()
    return asyncio.run(tool.run(spec or _spec(), tool_context(root, runner, params or None)))


